def _svg(name: str, color: str, stroke: float) -> bytes:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{_P[name]}</svg>').encode()


@lru_cache(maxsize=512)
def pixmap(name: str, color: str = "#F3F3F8", size: int = 20, stroke: float = 1.8, dpr: float = 2.0) -> QPixmap:
    px = QPixmap(int(size * dpr), int(size * dpr))
    px.fill(Qt.transparent)
    p = QPainter(px)
    p.setRenderHint(QPainter.Antialiasing)
    QSvgRenderer(_svg(name, color, stroke)).render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    px.setDevicePixelRatio(dpr)
    return px


def icon(name: str, color: str = "#F3F3F8", size: int = 20, stroke: float = 1.8) -> QIcon:
    return QIcon(pixmap(name, color, size, stroke))


def logo_pixmap(size: int = 128) -> QPixmap:
    """Logo LDC P2P : carré arrondi violet, deux nœuds reliés (pair à pair) et un reflet de verre."""
    dpr = 2.0
    s = size * dpr
    px = QPixmap(int(s), int(s))
    px.fill(Qt.transparent)
    p = QPainter(px)
    p.setRenderHint(QPainter.Antialiasing)
    r = QRectF(s * 0.04, s * 0.04, s * 0.92, s * 0.92)
    g = QLinearGradient(r.topLeft(), r.bottomRight())
    g.setColorAt(0, QColor("#A78BFA"))
    g.setColorAt(0.55, QColor("#7C3AED"))
    g.setColorAt(1, QColor("#4C1D95"))
    p.setBrush(g)
    p.setPen(Qt.NoPen)
    p.drawRoundedRect(r, s * 0.26, s * 0.26)
    # reflet verre
    shine = QPainterPath()
    shine.addRoundedRect(r, s * 0.26, s * 0.26)
    clip = QPainterPath()
    clip.addEllipse(QPointF(s * 0.30, s * -0.10), s * 0.85, s * 0.62)
    p.setClipPath(shine.intersected(clip))
    sg = QLinearGradient(0, 0, 0, s * 0.5)
    sg.setColorAt(0, QColor(255, 255, 255, 90))
    sg.setColorAt(1, QColor(255, 255, 255, 0))
    p.setBrush(sg)
    p.drawRect(r)
    p.setClipping(False)
    # deux nœuds reliés
    pen = QPen(QColor(255, 255, 255, 235), s * 0.07, Qt.SolidLine, Qt.RoundCap)
    p.setPen(pen)
    a, b = QPointF(s * 0.33, s * 0.60), QPointF(s * 0.67, s * 0.40)
    p.drawLine(a, b)
    p.setBrush(QColor("#FFFFFF"))
    p.setPen(Qt.NoPen)
    p.drawEllipse(a, s * 0.105, s * 0.105)
    p.drawEllipse(b, s * 0.105, s * 0.105)
    p.setBrush(QColor("#7C3AED"))
    p.drawEllipse(a, s * 0.045, s * 0.045)
    p.drawEllipse(b, s * 0.045, s * 0.045)
    p.end()
    px.setDevicePixelRatio(dpr)
    return px
